def print_splash_screen():
    """Display the animated splash screen."""
    import os

    # Clear screen
    os.system('clear' if os.name != 'nt' else 'cls')

    # Print heart art
    print("\033[91m" + HEART_ART + "\033[0m")  # Red heart

    # Brief pause
    time.sleep(0.5)

    # Print tagline
    print("\033[96m" + TAGLINE + "\033[0m")  # Cyan tagline

    # Animated "Press Enter"
    for _ in range(3):
        sys.stdout.write("\r" + " " * 100)  # Clear line
        sys.stdout.flush()
        time.sleep(0.3)
        sys.stdout.write("\r                                     Press ENTER to begin your journey...   ")
        sys.stdout.flush()
        time.sleep(0.3)

    print()  # New line
    input()  # Wait for user


